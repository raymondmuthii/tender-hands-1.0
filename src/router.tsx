import { QueryClient } from "@tanstack/react-query";
import { createRouter } from "@tanstack/react-router";
import { routeTree } from "./routeTree.gen";

/**
 * TanStack Router instance factory
 *
 * Creates a fresh router and QueryClient on each call. Called once on the
 * client and once per SSR request on the server to ensure request isolation.
 */
export const getRouter = () => {
  // Create a new QueryClient instance per router for SSR request isolation
  const queryClient = new QueryClient();

  const router = createRouter({
    routeTree,             // File-based route tree (auto-generated by TanStack Router)
    context: { queryClient }, // Pass queryClient through router context for use in routes
    scrollRestoration: true,  // Restore scroll position on back/forward navigation
    defaultPreloadStaleTime: 0, // Always re-fetch data on route preload
  });

  return router;
};
